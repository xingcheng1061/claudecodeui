#!/usr/bin/env node
/**
 * Regenerates the model snapshot (models.json) that
 * `claude-models.provider.ts` reads as the fallback layer of its catalogue.
 *
 * The primary source is the server's own runtime probe; this script exists for
 * the cases where that cannot answer — a deployment whose CLI is not
 * authenticated where the server runs, or an operator who wants to pin the
 * list before starting the server.
 *
 * Usage: node bin/refresh-models.mjs   (or ./refresh-models.sh)
 * Output: $CLOUDCLI_MODELS_FILE, or models.json in the repository root.
 * The server picks the file up on its next start.
 */

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { query } from '@anthropic-ai/claude-agent-sdk';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT_FILE = process.env.CLOUDCLI_MODELS_FILE || path.join(REPO_ROOT, 'models.json');

/** The CLI's own 'default' entry is an alias the API rejects; annotate, don't drop. */
const annotateDefaultEntry = (option) => {
  if (option.value !== 'default') {
    return option;
  }
  return {
    ...option,
    description: `${option.description ?? ''} (Warning: this alias has been observed to be rejected by the CLI; prefer a concrete model.)`.trim(),
  };
};

const toOption = (model) => {
  const base = annotateDefaultEntry({
    value: model.value,
    label: model.displayName || model.value,
    description: model.description || '',
  });

  if (!model.supportsEffort) {
    return base;
  }

  const levels = Array.isArray(model.supportedEffortLevels) && model.supportedEffortLevels.length > 0
    ? model.supportedEffortLevels
    : ['low', 'medium', 'high', 'max'];
  return {
    ...base,
    effort: {
      default: 'high',
      values: levels.map((value) => ({ value })),
    },
  };
};

const instance = query({ prompt: 'Get supported models' });

let models;
try {
  models = await instance.supportedModels();
} finally {
  try {
    instance.close();
  } catch {
    // Closing an already-dead query is noise, not a failure.
  }
}

const options = (models ?? [])
  .filter((model) => typeof model?.value === 'string' && model.value.trim())
  .map(toOption);

if (options.length === 0) {
  console.error(`[refresh-models] The CLI reported no models; nothing written to ${OUTPUT_FILE}.`);
  process.exit(1);
}

const snapshot = {
  _comment: 'Generated by bin/refresh-models.mjs: the model ids this deployment\'s Claude CLI reported as supported. Regenerate with ./refresh-models.sh after the CLI or gateway changes; the server reads this on start as the fallback layer behind its own runtime probe.',
  _generated: new Date().toISOString(),
  _source: 'claude-agent-sdk supportedModels()',
  OPTIONS: options,
};

await writeFile(OUTPUT_FILE, `${JSON.stringify(snapshot, null, 2)}\n`, 'utf8');
console.log(`[refresh-models] Wrote ${options.length} model(s) to ${OUTPUT_FILE}`);
