/**
 * Local snapshot of the model ids this deployment's Claude CLI actually accepts,
 * written by `bin/refresh-models.mjs`.
 *
 * Why a file and not runtime detection: `getSupportedModels()` would have to
 * spawn a real `claude` process (leaving a one-off session jsonl behind) on
 * every model-list request — the reason the upstream probe below stays
 * disabled. The snapshot is regenerated by hand when the CLI's models change;
 * it is not part of any startup flow.
 *
 * Resolution: `CLOUDCLI_MODELS_FILE` wins; otherwise `models.json` in the
 * working directory, which is the repo root on every documented launch path.
 */
const MODELS_FILE = process.env.CLOUDCLI_MODELS_FILE || path.join(process.cwd(), 'models.json');

/** Read once per process: the snapshot changes by hand, not while running. */
let fileModelsCache: ProviderModelsDefinition | null | undefined;

type ModelsSnapshot = {
  OPTIONS?: unknown;
};

/**
 * Loads the model snapshot, falling back to `null` on any problem — a missing,
 * corrupt, or empty file must degrade to the built-in catalogue, never make the
 * provider unable to answer at all.
 *
 * `DEFAULT` is always inherited from the built-in catalogue: the snapshot does
 * not carry one, and `ProviderModelsDefinition` requires it.
 */
const loadModelsFromFile = async (): Promise<ProviderModelsDefinition | null> => {
  if (fileModelsCache !== undefined) {
    return fileModelsCache;
  }

  try {
    const raw = await readFile(MODELS_FILE, 'utf8');
    const parsed = JSON.parse(raw) as ModelsSnapshot;
    const options = Array.isArray(parsed.OPTIONS)
      ? parsed.OPTIONS.filter(
        (option): option is ProviderModelOption =>
          Boolean(option) && typeof option === 'object' && typeof (option as ProviderModelOption).value === 'string' && (option as ProviderModelOption).value.trim().length > 0,
      )
      : [];

    if (options.length === 0) {
      throw new Error('snapshot has no usable OPTIONS entries');
    }

    fileModelsCache = { OPTIONS: options, DEFAULT: CLAUDE_PREDEFINED_MODELS.DEFAULT };
    console.log(`[claude] using ${options.length} model(s) from model snapshot ${MODELS_FILE}`);
  } catch (error) {
    // Silent when the file simply does not exist — that is the unconfigured
    // default. Anything else (corrupt JSON, empty snapshot) is worth a line.
    const isMissing = (error as NodeJS.ErrnoException)?.code === 'ENOENT';
    if (!isMissing) {
      console.warn(`[claude] model snapshot ${MODELS_FILE} unusable, using the built-in catalogue:`, error instanceof Error ? error.message : error);
    }
    fileModelsCache = null;
  }

  return fileModelsCache;
};

/* ------------------------------------------------------------------ */
/*  Runtime probe — the primary source, one attempt per server process */
/* ------------------------------------------------------------------ */

/** The shape the SDK's `supportedModels()` reports; loose so the mapper is testable. */
type ProbeableModelInfo = {
  value?: unknown;
  displayName?: unknown;
  description?: unknown;
  supportsEffort?: unknown;
  supportedEffortLevels?: unknown;
};

/**
 * Maps the CLI's `ModelInfo[]` into the provider catalogue shape.
 *
 * Effort levels come from the CLI when it reports them, defaulting to
 * low/medium/high/max; `xhigh`-capable models also get the ultracode option,
 * on the same rule the built-in catalogue uses. Returns null for input that
 * yields no usable entry, so the caller falls through to the next layer.
 */
export const buildClaudeModelsDefinitionFromModelInfos = (
  models: ProbeableModelInfo[],
): ProviderModelsDefinition | null => {
  const options = models
    .map((model): ProviderModelOption | null => {
      const value = typeof model.value === 'string' ? model.value.trim() : '';
      if (!value) {
        return null;
      }

      const label = typeof model.displayName === 'string' && model.displayName.trim()
        ? model.displayName
        : value;
      const description = typeof model.description === 'string' && model.description.trim()
        ? model.description
        : undefined;

      if (model.supportsEffort !== true) {
        return { value, label, ...(description ? { description } : {}) };
      }

      const reportedLevels = Array.isArray(model.supportedEffortLevels)
        ? model.supportedEffortLevels.filter((level): level is string => typeof level === 'string')
        : [];
      const levels = reportedLevels.length > 0 ? reportedLevels : ['low', 'medium', 'high', 'max'];

      return {
        value,
        label,
        ...(description ? { description } : {}),
        effort: {
          default: 'high',
          values: [
            ...levels.map((level) => ({ value: level })),
            ...(levels.includes('xhigh') ? [ULTRACODE_EFFORT_OPTION] : []),
          ],
        },
      };
    })
    .filter((option): option is ProviderModelOption => option !== null);

  return options.length > 0 ? { OPTIONS: options, DEFAULT: CLAUDE_PREDEFINED_MODELS.DEFAULT } : null;
};

/**
 * The probe talks to the CLI through a scratch working directory, so the
 * session jsonl it necessarily writes lands in its own project slug instead of
 * any real workspace's session list.
 */
const PROBE_SCRATCH_DIR = path.join(os.homedir(), '.cloudcli', 'model-probe');
const PROBE_TIMEOUT_MS = 60_000;

let probedModels: ProviderModelsDefinition | null | undefined;
let probeStarted = false;

/**
 * Removes probe transcripts older than an hour from the scratch project's
 * session folder. Best effort in every direction: a config dir that is not
 * where we expect (CLAUDE_CONFIG_DIR, custom runtime homes) means nothing is
 * found and nothing is deleted — the transcript simply stays bounded inside
 * the scratch slug, which is the part that matters.
 */
const cleanupProbeSessions = async (): Promise<void> => {
  try {
    const configDir = process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude');
    const projectDir = path.join(configDir, 'projects', `${PROBE_SCRATCH_DIR.replace(/[^a-zA-Z0-9]/g, '-')}`);
    const cutoff = Date.now() - 60 * 60 * 1000;
    const entries = await readdir(projectDir);
    await Promise.all(entries
      .filter((name) => name.endsWith('.jsonl'))
      .map(async (name) => {
        const filePath = path.join(projectDir, name);
        const stats = await stat(filePath);
        if (stats.mtimeMs < cutoff) {
          await unlink(filePath);
        }
      }));
  } catch {
    // Nothing to clean is the normal case.
  }
};

const runModelProbe = async (): Promise<void> => {
  try {
    await mkdir(PROBE_SCRATCH_DIR, { recursive: true });
    void cleanupProbeSessions();
  } catch {
    // A scratch dir that cannot be made only means the probe's transcript
    // lands somewhere less tidy; the probe itself can still run.
  }

  let instance: ReturnType<typeof query> | null = null;
  let probeTimer: NodeJS.Timeout | null = null;
  try {
    instance = query({
      prompt: 'Get supported models',
      options: { cwd: PROBE_SCRATCH_DIR },
    });

    const models = await Promise.race([
      instance.supportedModels(),
      new Promise<never>((_, reject) => {
        probeTimer = setTimeout(
          () => reject(new Error(`model probe timed out after ${PROBE_TIMEOUT_MS}ms`)),
          PROBE_TIMEOUT_MS,
        );
        probeTimer.unref?.();
      }),
    ]);

    probedModels = buildClaudeModelsDefinitionFromModelInfos(models);
    if (probedModels) {
      console.log(`[claude] model probe succeeded: ${probedModels.OPTIONS.length} model(s) reported by the CLI`);
    } else {
      console.warn('[claude] model probe returned no usable models; keeping the fallback catalogue');
    }
  } catch (error) {
    console.warn('[claude] model probe failed, keeping the fallback catalogue:', error instanceof Error ? error.message : error);
  } finally {
    if (probeTimer) {
      clearTimeout(probeTimer);
    }
    try {
      instance?.close();
    } catch {
      // Closing an already-dead query is noise, not a failure.
    }
  }
};

/** Starts the one-per-process probe. Never awaited, never throws. */
const kickOffModelProbe = (): void => {
  if (probeStarted) {
    return;
  }
  probeStarted = true;
  void runModelProbe();
};

export const findClaudeModelOption = (model: string | undefined | null): ProviderModelOption | null => {
  const normalizedModel = typeof model === 'string' ? model.trim() : '';
  if (!normalizedModel) {
    return null;
  }

  return CLAUDE_PREDEFINED_MODELS.OPTIONS.find((option) => option.value === normalizedModel) ?? null;
};
type ClaudeInitEvent = {
  sessionId?: string;
  session_id?: string;
  type?: string;
  subtype?: string;
  model?: string;
  message?: {
    content?: unknown;
    model?: string;
  };
};

/**
 * Claude Code stamps locally-synthesized rows (API-error placeholders and the
 * like) with `model: "<synthetic>"`. Angle-bracketed values are placeholders,
 * never real model ids, and must not be surfaced as the session's model.
 */
const isPlaceholderModel = (model: string): boolean => model.startsWith('<') && model.endsWith('>');

/** Exported for tests. */
export const extractClaudeEventModel = (event: ClaudeInitEvent, sessionId: string): string | null => {
  const eventSessionId = event.sessionId ?? event.session_id;
  if (eventSessionId && eventSessionId !== sessionId) {
    return null;
  }

  const contentModel = extractClaudeModelFromMessageContent(event.message?.content);
  if (contentModel) {
    return contentModel;
  }

  const directModel = event.model?.trim();
  if (directModel && !isPlaceholderModel(directModel)) {
    return directModel;
  }

  const messageModel = event.message?.model?.trim();
  return messageModel && !isPlaceholderModel(messageModel) ? messageModel : null;
};

const extractTaggedContent = (content: string, tagName: string): string | null => {
  const escapedTagName = tagName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = new RegExp(`<${escapedTagName}>([\\s\\S]*?)<\\/${escapedTagName}>`).exec(content);
  return match ? match[1] : null;
};

const extractClaudeModelFromTextContent = (content: string): string | null => {
  const localCommandStdout = extractTaggedContent(content, 'local-command-stdout');
  if (localCommandStdout !== null) {
    const cleanedStdout = stripAnsiSequences(localCommandStdout).replace(/\s+/g, ' ').trim();
    const changedModel = /(?:set|changed|switched)\s+model\s+to\s+(.+?)\.?$/i.exec(cleanedStdout);
    const stdoutModel = changedModel?.[1]?.trim();
    // A placeholder stdout hit must not shadow a real <model> tag further down.
    if (stdoutModel && !isPlaceholderModel(stdoutModel)) {
      return stdoutModel;
    }
  }

  const modelTag = extractTaggedContent(content, 'model')?.trim();
  return modelTag && !isPlaceholderModel(modelTag) ? modelTag : null;
};

const extractClaudeModelFromMessageContent = (content: unknown): string | null => {
  if (typeof content === 'string') {
    return extractClaudeModelFromTextContent(content);
  }

  if (!Array.isArray(content)) {
    return null;
  }

  for (const part of content) {
    if (!part || typeof part !== 'object' || !('text' in part) || typeof part.text !== 'string') {
      continue;
    }

    // extractClaudeModelFromTextContent rejects placeholders, so a placeholder
    // part yields null here and a later part can still supply the real model.
    const model = extractClaudeModelFromTextContent(part.text);
    if (model) {
      return model;
    }
  }

  return null;
};

const readClaudeSessionModelFromJsonl = async (
  sessionId: string,
  jsonlPath: string,
): Promise<ProviderCurrentActiveModel | null> => {
  const content = await readFile(jsonlPath, 'utf8');
  const lines = content
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);

  for (let index = lines.length - 1; index >= 0; index -= 1) {
    try {
      const event = JSON.parse(lines[index]) as ClaudeInitEvent;
      const model = extractClaudeEventModel(event, sessionId);
      if (model) {
        return { model };
      }
    } catch {
      // Skip malformed JSONL lines that can happen during concurrent writes.
    }
  }

  return null;
};

export class ClaudeProviderModels implements IProviderModels {
  async getSupportedModels(): Promise<ProviderModelsDefinition> {
    // Three layers, best source first:
    //   1. the runtime probe — what the CLI itself reports, once per process,
    //      run in the background so the first requests are not blocked on it;
    //   2. the models.json snapshot, regenerated by hand when models change;
    //   3. the built-in catalogue, which is always answerable.
    kickOffModelProbe();
    return probedModels ?? (await loadModelsFromFile()) ?? CLAUDE_PREDEFINED_MODELS;
  }

  async getCurrentActiveModel(sessionId?: string): Promise<ProviderCurrentActiveModel> {
    if (!sessionId?.trim()) {
      return buildDefaultProviderCurrentActiveModel(await this.getSupportedModels());
    }

    try {
      const jsonlPath = sessionsDb.getSessionById(sessionId)?.jsonl_path;
      const activeModel = jsonlPath
        ? await readClaudeSessionModelFromJsonl(sessionId, jsonlPath)
        : null;
      if (activeModel?.model) {
        return activeModel;
      }
    } catch {
      // Fall through to the provider default when the session-backed lookup fails.
    }

    return buildDefaultProviderCurrentActiveModel(await this.getSupportedModels());
  }
}
